"""TEST FIXTURE ONLY: a throwaway repo mimicking the TraceMind demo-app contract (NOT the real demo app).

Worker `process_message` does a plain INSERT into `notifications` (no UNIQUE) then acks; redelivery duplicates rows.
"""
from __future__ import annotations

import subprocess
from pathlib import Path

WORKER = '''"""FIXTURE notification worker (test fixture, not the real demo app)."""
import sqlite3


def init_db(conn: sqlite3.Connection) -> None:
    conn.execute("CREATE TABLE IF NOT EXISTS notifications (id INTEGER PRIMARY KEY, order_id TEXT NOT NULL, body TEXT)")
    conn.commit()


def ack(msg: dict) -> None:
    msg["acked"] = True


def process_message(conn: sqlite3.Connection, msg: dict) -> None:
    conn.execute("INSERT INTO notifications(order_id, body) VALUES (?, ?)", (msg["order_id"], msg["body"]))
    conn.commit()
    ack(msg)
'''

TEST_WORKER = '''import sqlite3

from worker import init_db, process_message


def test_single_delivery_inserts_one_row():
    conn = sqlite3.connect(":memory:")
    init_db(conn)
    msg = {"order_id": "o1", "body": "hi"}
    process_message(conn, msg)
    assert msg["acked"] is True
    assert conn.execute("SELECT COUNT(*) FROM notifications").fetchone()[0] == 1
'''

TEST_REDELIVERY = '''import sqlite3

from worker import init_db, process_message


def test_redelivery_does_not_duplicate_notification():
    """Scenario regression test: broker redelivers the same message after a missed ack."""
    conn = sqlite3.connect(":memory:")
    init_db(conn)
    for _ in range(2):
        process_message(conn, {"order_id": "o1", "body": "hi"})
    assert conn.execute("SELECT COUNT(*) FROM notifications WHERE order_id='o1'").fetchone()[0] == 1
'''

FIXED_WORKER = WORKER.replace(
    "order_id TEXT NOT NULL, body TEXT)", "order_id TEXT NOT NULL UNIQUE, body TEXT)"
).replace(
    'INSERT INTO notifications(order_id, body) VALUES (?, ?)"',
    'INSERT INTO notifications(order_id, body) VALUES (?, ?) ON CONFLICT(order_id) DO NOTHING"',
)


def _git(cwd: Path, *a: str) -> str:
    return subprocess.run(["git", "-c", "user.name=t", "-c", "user.email=t@t", *a], cwd=cwd, check=True,
                          capture_output=True, text=True).stdout


def make_fixture_repo(root: Path) -> Path:
    root.mkdir(parents=True)
    (root / "worker.py").write_text(WORKER)
    (root / "tests").mkdir()
    (root / "tests" / "test_worker.py").write_text(TEST_WORKER)
    (root / "tests" / "test_redelivery.py").write_text(TEST_REDELIVERY)
    (root / "conftest.py").write_text("import sys, pathlib\nsys.path.insert(0, str(pathlib.Path(__file__).parent))\n")
    _git(root, "init", "-q")
    _git(root, "add", "-A")
    _git(root, "commit", "-q", "-m", "fixture")
    return root


def real_fix_diff(tmp: Path) -> str:
    """Diff generated by git itself from a scratch copy, so hunks are exact."""
    scratch = tmp / "scratch_fix"
    scratch.mkdir()
    (scratch / "worker.py").write_text(WORKER)
    _git(scratch, "init", "-q"); _git(scratch, "add", "-A"); _git(scratch, "commit", "-q", "-m", "b")
    (scratch / "worker.py").write_text(FIXED_WORKER)
    return _git(scratch, "diff", "--no-color")
